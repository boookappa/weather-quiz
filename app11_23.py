# ==============================
if "answered" not in st.session_state:
    st.session_state.answered = {}

if "scores" not in st.session_state:
    st.session_state.scores = {
        difficulty: sum(
            question["point"]
            for i, question in enumerate(question_list)
            if st.session_state.answered.get(f"{difficulty}_{i}", False)
            and st.session_state.get(f"{difficulty}_{i}_correct", False)
        )
        for difficulty, question_list in questions.items()
    }

# ==============================
# 難易度選択
# ==============================
level = st.radio(
    "難易度を選択してください",
    ["やさしめ", "ふつう", "ハード", "鬼"],
    horizontal=True
)

st.divider()

# ==============================
# 問題表示
# ==============================
if len(questions[level]) == 0:

    st.info("🚧 この難易度の問題は準備中です！")

else:

    for i, q in enumerate(questions[level]):

        question_id = f"{level}_{i}"

        st.subheader(f"{level} 問題 {i + 1}")
        question_text = " ".join(q["question"].split())
        st.markdown(f"### {question_text}")
        st.write(f"配点：{q['point']}点")

        # 回答状態の初期化
        if question_id not in st.session_state.answered:
            st.session_state.answered[question_id] = False

        # ==============================
        # 回答ボタン
        # ==============================
        if not st.session_state.answered[question_id]:

            for option in q["options"]:

                if st.button(
                    option,
                    key=f"{question_id}_{option}",
                    use_container_width=True
                ):

                    st.session_state.answered[question_id] = True
                    st.session_state[f"{question_id}_user_answer"] = option

                    if option == q["answer"]:
                        st.session_state.scores[level] += q["point"]
                        st.session_state[f"{question_id}_correct"] = True
                    else:
                        st.session_state[f"{question_id}_correct"] = False

                    st.rerun()

        # ==============================
        # 回答後の表示
        # ==============================
        else:

            user_answer = st.session_state[f"{question_id}_user_answer"]

            if st.session_state[f"{question_id}_correct"]:
                st.success("🎉 正解！")
            else:
                st.error("残念、不正解！")

            st.write(f"あなたの回答：{user_answer}")
            st.write(f"正解：{q['answer']}")

            st.info(q["explanation"])

        st.divider()

# ==============================
